def week_dates(start, dur):
    a = W1 + timedelta(weeks=start - 1)
    b = a + timedelta(weeks=dur) - timedelta(days=3)  # до пятницы последней недели
    return a, b


def build():
    by_id = {t[0]: t for t in TASKS}
    dirs = []
    for code, name, owner in DIRS:
        ts = [t for t in TASKS if t[1] == code]
        w = sum(t[4] for t in ts)
        done = sum(t[3] * t[4] for t in ts)
        dirs.append({"code": code, "name": name, "owner": owner,
                     "pct": round(100 * done / w), "done_w": done, "w": w})

    # проверка зависимостей: задача не начинается раньше окончания предшественника
    warnings = []
    for tid, _, title, st, _, s, d, deps in TASKS:
        if s is None:
            continue
        for dep in deps:
            ds, dd = by_id[dep][5], by_id[dep][6]
            if ds is not None and ds + dd > s and st < 1:
                warnings.append(f"{tid} стартует на нед. {s}, а {dep} кончается на нед. {ds + dd - 1}")

    tasks = []
    for tid, code, title, st, w, s, d, deps in TASKS:
        item = {"id": tid, "dir": code, "title": title, "status": st, "weight": w, "deps": deps}
        if s is not None:
            a, b = week_dates(s, d) if s > 0 else (date(2026, 10, 14), date(2026, 10, 17))
            item.update(start=s, dur=d, from_=a.strftime("%d.%m"), to=b.strftime("%d.%m"))
        tasks.append(item)

    tw = sum(d["w"] for d in dirs)
    total = round(100 * sum(d["done_w"] for d in dirs) / tw)
    last = max(t[5] + t[6] - 1 for t in TASKS if t[5] is not None)
    weeks = [{"n": n, "mon": (W1 + timedelta(weeks=n - 1)).strftime("%d.%m")} for n in range(0, last + 1)]
    weeks[0]["mon"] = "12.10"
    # нагрузка: сколько задач идёт параллельно в каждую неделю
    load = [sum(1 for t in TASKS if t[5] is not None and t[3] < 1 and t[5] <= n < t[5] + t[6])
            for n in range(0, last + 1)]
    return {"asof": "16.10.2026", "total": total, "dirs": dirs, "tasks": tasks,
            "weeks": weeks, "load": load, "warnings": warnings}


def to_md(r):
    names = {d["code"]: d["name"] for d in r["dirs"]}
    L = [f"# Дорожная карта проекта\n",
         f"На {r['asof']}. Генерируется `scripts/roadmap.py` — правки статусов и сроков вносить в скрипт.",
         "Статус: ✅ сделано, ◐ начато, ○ не начато. Неделя 1 = 19.10.2026. "
         "ДОПУЩЕНИЕ: веса и длительности — экспертная оценка.\n",
         f"**Общий прогресс (по весу задач): {r['total']}%**\n",
         "| Направление | Ведёт | % |", "|---|---|---|"]
    for d in r["dirs"]:
        L.append(f"| {d['name']} | {d['owner']} | {d['pct']}% |")
    mark = {1: "✅", 0.5: "◐", 0: "○"}
    for d in r["dirs"]:
        L.append(f"\n## {d['name']} — {d['pct']}%\n")
        for t in [t for t in r["tasks"] if t["dir"] == d["code"]]:
            when = f" — нед. {t['start']}–{t['start'] + t['dur'] - 1} ({t['from_']}–{t['to']})" if "start" in t else ""
            deps = f"; после: {', '.join(t['deps'])}" if t["deps"] and t["status"] < 1 else ""
            L.append(f"- {mark[t['status']]} {t['id']} {t['title']}{when}{deps}")
    L.append("\n## Параллельная нагрузка (открытых задач в неделю)\n")
    L.append(" · ".join(f"н{w['n']}: {n}" for w, n in zip(r["weeks"], r["load"])))
    if r["warnings"]:
        L.append("\n## Конфликты зависимостей\n")
        L += [f"- {w}" for w in r["warnings"]]
    return "\n".join(L) + "\n"


