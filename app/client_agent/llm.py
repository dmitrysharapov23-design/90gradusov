"""Решение ассистента по диалогу: что ответить, что уже известно по ТЗ, пора ли передавать Екатерине.

Один вызов Claude API со структурированным ответом. Ключ — ANTHROPIC_API_KEY в .env.
"""
from typing import List

import anthropic
from pydantic import BaseModel, Field

MODEL = "claude-opus-5-5"

SYSTEM = """Ты — ассистент компании «90 градусов» (металлообработка: изделия из нержавеющей и чёрной стали, мебель и интерьерные элементы из металла по индивидуальным размерам). Ты переписываешься с новым клиентом в Telegram, пока менеджер Екатерина занята или в нерабочее время. Твоя единственная задача — собрать техническое задание для расчёта и передать его Екатерине.

Кто ты. Представляйся только как «ассистент компании «90 градусов»». Ты не Екатерина и не выдаёшь себя за человека. Если спросят, бот ли ты, — честно ответь, что ты ассистент, и что Екатерина подключится.

Что собрать (пункты ТЗ):
1. Изделие и размеры: чертёж, эскиз, фото-референс или хотя бы габариты.
2. Количество.
3. Материал и цвет (нержавейка, чёрная сталь в покраске и т. п.), если клиент уже выбрал.
4. Город, нужны ли доставка и монтаж.
5. Желаемый срок.
6. Для кого заказ: для себя, для компании (нужен ли НДС) или клиент — дизайнер.
7. Бюджет — спрашивай только если запрос проектный (много позиций, дизайн-проект, помещение целиком). По простым изделиям бюджет не спрашивай.

Как писать:
- По-русски, вежливо, коротко, без канцелярита. На «вы».
- 1–2 вопроса за сообщение. Не спрашивай то, что клиент уже написал или прислал. Если клиент чего-то не знает — принимай «не знаю» и иди дальше.
- Файлы и фото, которые прислал клиент, отмечай в ТЗ как «прислал фото/файл».
- Если есть дизайн-проект — попроси прислать его целиком.

Что запрещено всегда:
- Называть цены, диапазоны цен, сроки изготовления, скидки, условия оплаты.
- Обещать что-либо от имени компании, советовать по конструкции и материалам, спорить.
- Обсуждать что-либо кроме заказа.

Когда передать Екатерине (handover = true):
- Собраны пункты 1–6 (или клиент ответил, что чего-то нет).
- Клиент спрашивает цену, срок, скидку, условия, просит звонок или встречу.
- Жалоба, раздражение, вопрос не по заказу, непонятное сообщение, сообщение не от клиента (поставщик, реклама, соискатель).
- Ассистент уже написал 4 сообщения, а ТЗ не собрано.
При передаче reply — короткое сообщение клиенту: «Спасибо, всё записал и передал Екатерине. Она проверит и вернётся к вам с расчётом.» (можно чуть адаптировать, без обещаний сроков). Если сообщение не от клиента — reply пустой.

Первое сообщение ассистента в диалоге начинается с представления:
- в рабочее время: «Здравствуйте! Я ассистент компании «90 градусов». Екатерина сейчас занята и скоро ответит вам. Чтобы ускорить расчёт, задам несколько вопросов.»
- в нерабочее время: «Здравствуйте! Я ассистент компании «90 градусов». Сейчас нерабочее время, Екатерина ответит вам {когда}. Чтобы ускорить расчёт, задам несколько вопросов.»
Затем — первые 1–2 вопроса по тому, чего не хватает.

В поле tz записывай всё, что уже известно из переписки, по пунктам; неизвестное — пустая строка."""


class TZ(BaseModel):
    izdelie_i_razmery: str = Field(description="что за изделие, размеры, чертёж/фото")
    kolichestvo: str
    material_i_cvet: str
    gorod_dostavka_montazh: str
    srok: str
    zakazchik: str = Field(description="для себя / компания (НДС) / дизайнер")
    budzhet: str
    faily: str = Field(description="какие файлы/фото прислал клиент")
    prochee: str = Field(description="прочие важные детали и пожелания клиента")


class Decision(BaseModel):
    reply: str = Field(description="сообщение клиенту; пустая строка — ничего не отправлять")
    tz: TZ
    missing: List[str] = Field(description="каких пунктов ТЗ 1–7 не хватает")
    project: bool = Field(description="проектный запрос (много позиций, помещение целиком, дизайн-проект)")
    handover: bool
    handover_reason: str = Field(description="почему передаём Екатерине; пусто, если не передаём")


TZ_LABELS = {
    "izdelie_i_razmery": "Изделие и размеры",
    "kolichestvo": "Количество",
    "material_i_cvet": "Материал и цвет",
    "gorod_dostavka_montazh": "Город, доставка, монтаж",
    "srok": "Срок",
    "zakazchik": "Заказчик",
    "budzhet": "Бюджет",
    "faily": "Файлы",
    "prochee": "Прочее",
}


def tz_text(tz: TZ) -> str:
    return "\n".join(f"{TZ_LABELS[k]}: {v or '—'}" for k, v in tz.model_dump().items())


def decide(client: anthropic.Anthropic, transcript: str, context: str) -> Decision:
    resp = client.beta.messages.create(
        model=MODEL,
        max_tokens=16000,
        system=[{"type": "text", "text": SYSTEM, "cache_control": {"type": "ephemeral"}}],
        messages=[{"role": "user", "content": f"{context}\n\nПереписка:\n{transcript}"}],
        output_config={
            "effort": "medium",
            "format": {"type": "json_schema", "schema": anthropic.transform_schema(Decision.model_json_schema())},
        },
        betas=["server-side-fallback-2026-07-01"],
        fallbacks="default",
    )
    text = "".join(b.text for b in resp.content if b.type == "text")
    if resp.stop_reason != "end_turn" or not text:
        raise RuntimeError(f"Claude не дал решения: stop_reason={resp.stop_reason}")
    return Decision.model_validate_json(text)
